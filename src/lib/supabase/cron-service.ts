import type { SupabaseClient } from "@supabase/supabase-js";

/**
 * Cron service-account sign-in (migration 0036 follow-up).
 *
 * Migration 0036 revoked the anon grant on every sensitive SECURITY
 * DEFINER helper RPC (view refresh, cleanup, hold release), so the
 * GitHub Actions cron routes can no longer call them with the anon
 * key and no session. The routes now sign in as a dedicated
 * service account — a normal creator-role user, NOT an admin — and
 * use that session for every Supabase call in the request.
 *
 * Env vars (Vercel Production, set by the owner):
 *   CRON_SERVICE_EMAIL    — e.g. cron@get-paid-to-post.vercel.app
 *   CRON_SERVICE_PASSWORD — generated by the owner, never in git
 *
 * The account itself is created once in Supabase Auth (auto-
 * confirmed, no mail needed — it never receives mail). An admin
 * already exists, so handle_new_user() makes it a plain creator.
 *
 * FAIL LOUD: returns an error string when the env vars are missing
 * or the sign-in fails. Callers return 503 with it — a cron run
 * must never silently do nothing, and must never fall back to the
 * anon key for the revoked RPCs. Returns null on success.
 *
 * No service_role key is used anywhere.
 */
export async function signInCronService(
  supabase: SupabaseClient
): Promise<string | null> {
  const email = process.env.CRON_SERVICE_EMAIL;
  const password = process.env.CRON_SERVICE_PASSWORD;
  if (!email || !password) {
    return (
      "Cron service account is not configured: set CRON_SERVICE_EMAIL " +
      "and CRON_SERVICE_PASSWORD in Vercel (Production). Migration " +
      "0036 revoked the anon grant on the cron RPCs, so the job " +
      "cannot run without it."
    );
  }
  const { data, error } = await supabase.auth.signInWithPassword({
    email,
    password,
  });
  if (error) {
    return `Cron service sign-in failed: ${error.message}`;
  }
  if (!data.session) {
    return "Cron service sign-in failed: no session returned.";
  }
  return null;
}
